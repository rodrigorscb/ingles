import type { A1Module, Lesson } from "@/lib/course";

type Phrase = [string, string, string];
type Exercise = [string, string[], number, string];
type LessonSeed = {
  id: string;
  title: string;
  subtitle: string;
  objective: string;
  duration: number;
  focus: string;
  intro: string;
  phrases: Phrase[];
  grammarTitle: string;
  grammar: string;
  examples: [string, string][];
  practice: Exercise[];
  takeaway: string;
};

function buildLesson(seed: LessonSeed): Lesson {
  return {
    id: seed.id,
    slug: seed.id,
    title: seed.title,
    subtitle: seed.subtitle,
    objective: seed.objective,
    duration: seed.duration,
    focus: seed.focus,
    intro: seed.intro,
    phrases: seed.phrases.map(([english, portuguese, note]) => ({ english, portuguese, note })),
    grammar: {
      title: seed.grammarTitle,
      explanation: seed.grammar,
      examples: seed.examples.map(([english, portuguese]) => ({ english, portuguese })),
    },
    practice: seed.practice.map(([prompt, options, answer, explanation]) => ({ prompt, options, answer, explanation })),
    takeaway: seed.takeaway,
  };
}

